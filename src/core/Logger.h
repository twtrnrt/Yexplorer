// ============================================================================
// 文件管理器（自研 Explorer 替代品）
// 文件：src/core/Logger.h
//
// 日志封装（基于 spdlog，header-only 模式，无额外 dll）。
//
// 为什么需要日志：
//   这个项目大量使用 COM，出错时往往只是返回一个 HRESULT，不弹窗、不崩溃，
//   现象表现为"什么都没有"。必须有日志把每一步的 HRESULT 和路径记下来，
//   否则排查起来只能瞎猜。
// ============================================================================

#pragma once

#include <string>

namespace Logger
{

// ----------------------------------------------------------------------------
// 初始化日志
// 参数：logFilePath —— 日志文件绝对路径（UTF-16）
// 说明：失败时静默返回（日志不可用不应导致程序启动失败）
// ----------------------------------------------------------------------------
void Init(const std::wstring& logFilePath);

// 关闭日志（进程退出前调用，确保缓冲区刷盘）
void Shutdown();

// ----------------------------------------------------------------------------
// 取当前日志文件的绝对路径（未初始化时返回空串）
//
// 用途：目录监视（FolderWatcher）要跳过"日志自己增长"这种变化。
// 日志文件就在 exe 旁边，用户停在 exe 所在目录时，每写一行日志都会让
// 监视器以为"目录变了"，刷新目录、刷新又写日志 —— 会变成死循环。
// ----------------------------------------------------------------------------
std::wstring FilePath();

// 普通信息（参数为 UTF-16 字符串，内部转 UTF-8 写入）
void Info(const std::wstring& message);

// 警告
void Warn(const std::wstring& message);

// 错误（建议带上 HRESULT 描述，用 FormatHresult 辅助）
void Error(const std::wstring& message);

// ----------------------------------------------------------------------------
// 把 HRESULT 转成可读文本（十六进制码 + 系统消息），便于日志排查
// ----------------------------------------------------------------------------
std::wstring FormatHresult(long hr);

} // namespace Logger
