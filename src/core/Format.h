// ============================================================================
// 文件管理器（自研 Explorer 替代品）
// 文件：src/core/Format.h
//
// 显示格式化工具：把原始数据转成列表/界面要显示的文本。
//
// 单独抽成一个模块的原因：
//   这些格式化逻辑会被列表控件、状态栏、日志多处复用，
//   放在任何一个 UI 文件里都会造成重复代码。
// ============================================================================

#pragma once

#include <windows.h>
#include <string>
#include <cstdint>

namespace format
{

// ----------------------------------------------------------------------------
// FILETIME（UTC）→ 本地时间文本 "YYYY-MM-DD HH:MM"
// 时间全为 0（取不到）时返回 "-"
// ----------------------------------------------------------------------------
std::wstring FileTimeText(const FILETIME& utcFileTime);

// ----------------------------------------------------------------------------
// 字节数 → 易读大小，例如 "109.9 KB"、"1.25 GB"
// 文件夹统一返回 "文件夹"
// 单位按 1024 进位逐级升：B → KB → MB → GB → TB → PB → EB
// ----------------------------------------------------------------------------
std::wstring SizeText(uint64_t size, bool isFolder);

// ----------------------------------------------------------------------------
// 磁盘容量专用文本（「此电脑」平铺卡片上用）
//   "97.7 GB 可用，共 234 GB" 里的那两个数字就是它。
// 同样是 1024 进位，按 3 位有效数字显示：
//   234 GB → "234 GB"，97.7 GB → "97.7 GB"，1 TB → "1.00 TB"
// ----------------------------------------------------------------------------
std::wstring CapacityText(uint64_t bytes);

// ----------------------------------------------------------------------------
// 文件类型文本
//   文件夹 → "文件夹"
//   .dll   → "DLL 文件"
//   无扩展名 → "文件"
// ----------------------------------------------------------------------------
std::wstring TypeText(const std::wstring& name, bool isFolder);

} // namespace format
