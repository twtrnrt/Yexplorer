// ============================================================================
// 文件管理器（自研 Explorer 替代品）
// 文件：src/shell/ShellFolder.h
//
// Shell 层：目录枚举接口。
//
// 关键设计决定（很重要，接手时先看懂这条）：
//   1. 用 IShellFolder 而不是 FindFirstFile。
//      FindFirstFile 只能读真实文件系统目录；IShellFolder 是资源管理器用的同一套
//      命名空间接口，能枚举「此电脑」「回收站」「网络」这些虚拟文件夹，
//      也能枚举压缩包内部（如果系统装了压缩外壳）。
//
//   2. 返回的是「纯数据快照」（ShellEntry），不返回任何 COM 指针。
//      原因：COM 对象有套间（apartment）归属，跨线程传递很容易崩。
//      后台线程内部自己创建、自己释放 COM 对象，只把数据交出去，最安全。
//
//   3. 单个文件夹枚举不设条数上限，但支持取消：用户快速切目录时，
//      上一个枚举立即中断，不会堆积后台任务。
// ============================================================================

#pragma once

#include <windows.h>
#include <string>
#include <vector>
#include <cstdint>

#include "../core/AsyncTask.h"

namespace shell
{

// ----------------------------------------------------------------------------
// 一个 Shell 条目的数据快照（无 COM 指针，可自由跨线程复制传递）
// ----------------------------------------------------------------------------
struct ShellEntry
{
    std::wstring name;              // 显示名（文件名或虚拟项名称）
    std::wstring fullPath;          // 绝对路径；虚拟项（如「此电脑」）可能为空
    bool         isFolder = false;  // 是否文件夹
    uint64_t     size     = 0;      // 文件大小（字节）；文件夹固定为 0
    FILETIME     modified = {};     // 修改时间（UTC）；取不到时全为 0
};

// ----------------------------------------------------------------------------
// 一次枚举的结果
// ----------------------------------------------------------------------------
struct EnumerateResult
{
    std::wstring            path;          // 被枚举的路径
    long                    hr = E_FAIL;   // 枚举是否成功（S_OK 表示成功）
    std::vector<ShellEntry> entries;       // 条目列表
    size_t                  folderCount = 0;
    size_t                  fileCount   = 0;
    bool                    cancelled   = false;  // 是否因取消而提前中断
};

// ----------------------------------------------------------------------------
// 命名空间最顶层的「桌面」容器
//
// 资源管理器里从「此电脑」再点向上，会到一个叫「桌面」的地方，里面是
// 此电脑、回收站、控制面板、主文件夹、音乐、图片、视频、文档、下载、桌面、图库、网络…
// 再加桌面上的那些文件。它是虚拟文件夹，没有可用的解析名（系统自己的
// Path 属性会返回 C:\Users\X\Desktop，但那是另一个东西——只有桌面上的文件）。
//
// 所以这里用一个约定的伪路径在程序内部表示它；枚举时改用 SHGetDesktopFolder
// 拿到的桌面根文件夹，效果和资源管理器那层一样。
// ----------------------------------------------------------------------------
constexpr const wchar_t* kTopDesktopPath = L"::TopDesktop";

inline bool IsTopDesktopPath(const std::wstring& path)
{
    return ::_wcsicmp(path.c_str(), kTopDesktopPath) == 0;
}

// 「此电脑」的解析名（资源管理器地址栏里也就是这个）
constexpr const wchar_t* kThisPcPath = L"::{20D04FE0-3AEA-1069-A2D8-08002B30309D}";

// ----------------------------------------------------------------------------
// 枚举指定路径下的所有条目
//
// 参数：
//   path  —— 目录绝对路径，例如 L"C:\\"、L"C:\\Windows"
//   token —— 取消令牌，可为 nullptr（表示不可取消）
//
// 返回：EnumerateResult（含 hr 状态码）
//
// 线程说明：可在任意线程调用。函数内部会自行 CoInitializeEx 并 CoUninitialize，
//           不依赖调用线程是否已初始化 COM。
// ----------------------------------------------------------------------------
EnumerateResult EnumerateFolder(const std::wstring& path,
                                const core::CancellationToken* token);

// ----------------------------------------------------------------------------
// 取「上一级」（就是资源管理器那个「向上」按钮走的那套逻辑）
//
// 关键点：这里不是把路径字符串砍掉最后一段，而是交给 Shell 命名空间去算父项：
//   下载                     → kf168（用户主文件夹）    ← 字符串截断也会得到这个
//   C:\Users\kf168\Desktop   → C:\Users\kf168
//   C:\                      → 此电脑（::{20D04FE0-...}）
//   此电脑                   → 桌面（命名空间顶层那个「桌面」，里面含此电脑、
//                              主文件夹、音乐、图片等）—— 字符串截断算不出这一层
//   桌面（顶层）             → 没有上一级（返回空串，向上按钮就该变灰）
//
// 参数 path 可以是文件系统路径，也可以是 "::{GUID}" 或 "shell:xxx" 这种 Shell 路径。
// 返回：上一级的绝对解析名（可直接拿去导航）；没有上一级时返回空串。
// 严格来说传进来的路径本身就无效、或者本来就在顶层时返回空串。
// ----------------------------------------------------------------------------
std::wstring GetParentPath(const std::wstring& path);

// ----------------------------------------------------------------------------
// 判断一个 Shell 项"到底是不是容器"（能不能当作文件夹导航进去）
//
// 为什么要这个：控制面板里像「恢复」「凭据管理器」「Windows Defender 防火墙」
// 这些项，属性上算文件夹（SFGAO_FOLDER 为真），但其实是个 applet——
// 双击应该弹出一个设置界面，而不是往里导航。直接导航只会得到一个空列表，
// 用户看到的就是"双击打不开、只显示一个空文件夹"。
// 资源管理器的做法是：是容器就进去，不是容器就当"打开"处理。
//
// 判定办法：能不能绑定出一个 IShellFolder 并且枚举接口可用。
//   能 → 是容器（哪怕里面是空的，比如空回收站，也应该导航进去显示空列表）
//   不能 → 不是容器（applet），交给 ShellExecute 去打开
//
// 参数用解析名（文件系统路径或 "::{GUID}…" 都行）。
// 注意：会真的去 BindToObject / EnumObjects 一次，结果不缓存；
// 只在双击时调用，开销可忽略。
// ----------------------------------------------------------------------------
bool ShellItemIsContainer(const std::wstring& path);

} // namespace shell
